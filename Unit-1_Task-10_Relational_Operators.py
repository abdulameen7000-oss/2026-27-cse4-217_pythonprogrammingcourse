# Write a python program to demonstrate relational operators (print comparison results)

# Input two numbers
a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

# Demonstrate relational operators
print("a == b :", a == b)
print("a != b :", a != b)
print("a > b  :", a > b)
print("a < b  :", a < b)
print("a >= b :", a >= b)
print("a <= b :", a <= b)